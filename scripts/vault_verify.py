def fixture_values(vb) -> dict:
    """The values the fixture pins (section 14, FIXTURES)."""
    facets = {}
    for k, p in vb.principles.items():
        facets[str(k)] = [{"title": f.title_ar, "kind": f.entry_kind, "label": f.page_label, "refs": [r.ref_ar for r in f.references]} for f in p.facets]
    numbers_per_page: dict[str, list[int]] = {}
    for b in vb.parse.blocks:
        numbers_per_page.setdefault(str(b.page), [])
        numbers_per_page[str(b.page)] += [int(n) for n in b.numbers if n.isdigit()]
    shared = sorted({tuple(sorted(int(n) for n in b.numbers if n.isdigit())) for b in vb.parse.blocks if len(b.numbers) > 1})
    siblings = []
    for b in vb.parse.blocks:
        if b.continues_block is not None:
            prev = vb.parse.blocks[b.continues_block]
            siblings.append([sorted(int(n) for n in prev.numbers if n.isdigit()), sorted(int(n) for n in b.numbers if n.isdigit()), b.kind])
    see_also = [{"numbers": sorted(int(n) for n in b.numbers if n.isdigit()), "path": vm._see_also_path(b.see_also_text)} for b in vb.parse.blocks if b.kind == "see_also"]
    subtopics = [{"letter": L.letter, "topic": T.title_ar, "subtopics": [(s["label"], s["title"]) for s in T.subtopics]} for L in vb.parse.letters for T in L.topics]
    return {
        "page_classes": {str(k): v for k, v in vb.parse.page_classes.items()},
        "page_labels": {str(k): v for k, v in vb.parse.page_labels.items()},
        "letters": [L.letter for L in vb.parse.letters],
        "topics": [T.title_ar for L in vb.parse.letters for T in L.topics],
        "subtopics": [{"letter": s["letter"], "topic": s["topic"], "subtopics": [list(x) for x in s["subtopics"]]} for s in subtopics],
        "principle_numbers": sorted(int(vm.key_number(n)) for n in vb.principles),
        "numbers_per_page": numbers_per_page,
        "blocks_per_page": {str(k): v for k, v in sorted(collections.Counter(b.page for b in vb.parse.blocks).items())},
        "shared_entries": [list(s) for s in shared],
        "sibling_pairs": siblings,
        "see_also_entries": see_also,
        "ruling_references": sorted({r.ref_ar for p in vb.principles.values() for r in p.references}),
        "facets": facets,
        "held": sorted(vb.held, key=vm.key_sort),
    }


def check_fixture(project, vb, rep: Report) -> None:
    path = project.root / "tests" / "fixtures" / f"{vb.vid}.expected.yaml"
    if not path.exists():
        rep.add("fixture comparison", True, "no fixture file")
        return
    exp = em.load_yaml(path.read_text(encoding="utf-8"))
    got = em.load_yaml(em.dump_yaml(fixture_values(vb)))
    problems = []
    for key, value in got.items():
        if key in exp and exp[key] != value:
            problems.append(key)
    rep.add("fixture expectations", not problems, "; ".join(problems[:5]) or f"{len([k for k in got if k in exp])} fixture keys compared")


def content_checks(vb, files: dict[str, str], vault_root: Path | None, prefix: str) -> Report:
    """The checks that must reject a corrupted copy: structure, frontmatter, wording, links."""
    rep = Report()
    check_vault_files(files, rep, vault_root, prefix)
    check_frontmatter_against_records(vb, files, rep)
    check_wording_equality(vb, files, rep)
    return rep


def mutation_test(vb, files: dict[str, str], vault_root: Path | None, prefix: str, rep: Report) -> None:
    """Each mutation of a temporary copy must be rejected by a content check (acceptance item 7)."""
    baseline = content_checks(vb, files, vault_root, prefix)
    if not baseline.ok:
        rep.add("mutated temporary copy is rejected", False, "baseline copy fails the content checks: " + "; ".join(baseline.failures()[:2]))
        return
    keys = [k for k in sorted(vb.principles, key=vm.key_sort) if k not in vb.held and vb.principles[k].facets[0].wording_paragraphs]
    if not keys:
        rep.add("mutated temporary copy is rejected", False, "no published principle with wording to mutate")
        return
    key = keys[0]
    rel = f"Principles/{vm.principle_filename(key)}"
    front_text, body = split_front(files[rel])
    facet = vb.principles[key].facets[0]
    para = facet.wording_paragraphs[0]
    ref = facet.reference_line
    label = em.g_id(facet.page_label) if facet.page_label else ""
    idx_front, idx_body = split_front(files["index.md"]) if "index.md" in files else ("", "")

    def rebuild(front_t: str, body_t: str) -> str:
        return "---\n" + front_t + "---\n" + body_t

    mutations: dict[str, tuple[str, str, str] | None] = {
        "index wording": ("body", em.md_escape(para), em.md_escape(para[:-1] + ("ـ" if para[-1] != "ـ" else "x"))),
        "body wording": None,
        "YAML": ("front", "principle_id:", "principle_id: \"x\"\nprinciple_id:"),  # a duplicate key: structural corruption
        "link": ("index", f"Principles/{vm.principle_filename(key)})", f"Principles/x{vm.principle_filename(key)})"),
        "ruling reference": ("body", em.md_escape(ref), em.md_escape(ref.replace("1", "7", 1))) if ref else None,
        "number": ("front", f'principle_number: "{vm.key_number(key)}"', f'principle_number: "{vm.key_number(key)}9"'),
        "page label": ("front", f'page_id: "{label}"', f'page_id: "{label}9"') if label else None,
    }
    results = []
    all_ok = True
    for name, mut in mutations.items():
        if mut is None:
            results.append(f"{name}: not applicable")
            continue
        where, old, new = mut
        source = front_text if where == "front" else (idx_body if where == "index" else body)
        if old not in source:
            results.append(f"{name}: pattern not found")
            all_ok = False
            continue
        mutated_text = source.replace(old, new, 1)
        mutated = dict(files)
        if where == "index":
            mutated["index.md"] = rebuild(idx_front, mutated_text)
        else:
            mutated[rel] = rebuild(mutated_text, body) if where == "front" else rebuild(front_text, mutated_text)
        sub = content_checks(vb, mutated, vault_root, prefix)
        rejected = not sub.ok
        all_ok = all_ok and rejected
        results.append(f"{name}: {'rejected (' + sub.failures()[0].split(':')[0] + ')' if rejected else 'NOT rejected'}")
    rep.add("mutated temporary copy is rejected", all_ok, "; ".join(results))


def _manifest(files: dict[str, str]) -> str:
    h = hashlib.sha256()
    for k in sorted(files):
        h.update(k.encode("utf-8"))
        h.update(hashlib.sha256(files[k].encode("utf-8")).digest())
    return h.hexdigest()


