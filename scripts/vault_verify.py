def _pdftotext_path() -> str | None:
    env = os.environ.get("PRINCIPLES_VAULT_PDFTOTEXT")
    if env and Path(env).exists():
        return env
    return shutil.which("pdftotext")


RE_BIDI_MARKS = re.compile(r"[\u200e\u200f\u202a-\u202e\u2066-\u2069]")


def _norm_second_reader(text: str) -> str:
    t = unicodedata.normalize("NFKC", text)
    t = re.sub(r"\ufffd", "", RE_BIDI_MARKS.sub("", t))
    return ps.western_digits(t)


def pdftotext_page(tool: str, path, pno: int) -> str:
    """The second reader's text of one physical page (Poppler pdftotext -layout), normalized."""
    out = subprocess.run([tool, "-layout", "-f", str(pno), "-l", str(pno), str(path), "-"], capture_output=True, text=True, encoding="utf-8", errors="replace")
    return _norm_second_reader(out.stdout)


def second_reader_confirms(published: str, page_text: str) -> bool:
    """True when the second reader positively confirms a published line on its page: every number of the line occurs
    in the page's numbers, and every word occurs on the page (letter skeleton), or with the same letters in another
    order (the reader's known ligature reversal). A line with neither words nor numbers is never confirmed."""
    if not page_text or not published.strip():
        return False
    page_numbers = set(re.findall(r"[0-9]+", page_text))
    numbers = re.findall(r"[0-9]+", published)
    words = [w for w in (vm.skeleton(re.sub(r"[0-9]+", " ", t)) for t in published.split()) if w]
    if not numbers and not words:
        return False
    if any(n not in page_numbers for n in numbers):
        return False
    tokens = [vm.skeleton(re.sub(r"[0-9]+", " ", t)) for t in page_text.split()]  # digits are compared as numbers above
    tokens = [t for t in tokens if t]
    # the second reader may split one word into adjacent tokens at a glyph it cannot decode ("ق�صور ًا"): two and
    # three adjacent tokens joined are candidates too; every letter must still agree
    page_words = set(tokens) | {a + b for a, b in zip(tokens, tokens[1:])} | {a + b + c for a, b, c in zip(tokens, tokens[1:], tokens[2:])}
    page_sorted = {"".join(sorted(w)) for w in page_words}
    # the second reader may also run adjacent words together («تقديرهللبينات»): a word of at least
    # RUN_TOGETHER_MIN_LETTERS letters is found inside one of its tokens; a shorter word needs a token of its own
    joined = " ".join(tokens)
    return all(w in page_words or "".join(sorted(w)) in page_sorted
               or (len(w) >= RUN_TOGETHER_MIN_LETTERS and w in joined) for w in words)


RUN_TOGETHER_MIN_LETTERS = 4


def cmd_crosscheck(project, volume_ids: list[str]) -> int:
    import pipeline  # noqa: E402

    rc = 0
    for vid in volume_ids:
        cfg = project.load_config(vid)
        run = pipeline.current_run(project, vid)
        lines = [f"# Cross-check report — {vid} (run {run})", ""]
        tool = _pdftotext_path()
        if tool is None:
            lines += ["RESULT: NO SECOND READER", "", "pdftotext was not found (PRINCIPLES_VAULT_PDFTOTEXT, PATH)."]
            _write_report(project, vid, f"crosscheck-r{run}", "\n".join(lines))
            print("\n".join(lines))
            continue
        entries = [e for e in cfg.get("source_files", []) if e.get("kind") == "index"]
        failed = False
        page_text: dict[str, dict[int, str]] = {}
        for entry in entries:
            path = project.source_path(vid, entry)
            if not path.exists():
                lines += [f"- {path.name}: missing"]
                failed = True
                continue
            if pipeline.sha256_file(path) != entry.get("sha256"):
                lines += [f"- {path.name}: SHA-256 differs from the configuration"]
                failed = True
                continue
            try:
                doc = pymupdf.open(str(path))
                n = len(doc)
                doc.close()
            except Exception as exc:  # noqa: BLE001
                lines += [f"- {path.name}: unreadable ({exc})"]
                failed = True
                continue
            page_text[path.name] = {}
            for pno in range(1, n + 1):
                out = subprocess.run([tool, "-layout", "-f", str(pno), "-l", str(pno), str(path), "-"], capture_output=True, text=True, encoding="utf-8", errors="replace")
                page_text[path.name][pno] = _norm_second_reader(out.stdout)
        if failed:
            lines.insert(2, "RESULT: FAIL")
            _write_report(project, vid, f"crosscheck-r{run}", "\n".join(lines))
            print("\n".join(lines[:6]))
            rc = 1
            continue
        vb, _files = pipeline.build_volume_files(project, vid)
        counts: collections.Counter = collections.Counter()
        details = []
        for key in sorted(vb.principles, key=vm.key_sort):
            p = vb.principles[key]
            cls_of_facets = []
            words_missing_vault: list[str] = []
            words_missing_reader: list[str] = []
            for f in p.facets:
                page = page_text.get(f.file, {}).get(f.page, "")
                page_skeleton = vm.skeleton(page)
                reader_words = [vm.skeleton(w) for w in page.split()]
                reader_sorted = collections.Counter("".join(sorted(w)) for w in reader_words if w)
                digits = [str(p.number)] + ([f.page_label] if f.page_label else []) + [d for r in f.references for d in r.number.split("-")]
                numbers_ok = all(d in page for d in digits)
                words = [w for w in (vm.skeleton(w) for para in f.wording_paragraphs for w in para.split()) if w]
                missing_exact = [w for w in words if w not in page_skeleton]
                missing_sorted = [w for w in missing_exact if reader_sorted["".join(sorted(w))] == 0]
                if not numbers_ok:
                    cls_of_facets.append("not found")
                elif not missing_exact:
                    cls_of_facets.append("identical")
                elif not missing_sorted:
                    cls_of_facets.append("letters present in another order")
                else:
                    cls_of_facets.append("word differences")
                    words_missing_vault += missing_sorted
                # the reverse direction: words of the second reader's rendering of this facet's lines absent from the vault,
                # with the reader's known defects filtered (ligature reversals: same letters in another order)
                vault_sorted = collections.Counter("".join(sorted(w)) for w in words)
                block = vb.parse.blocks[f.block_index]
                block_text = " ".join(l.text for l in block.wording_lines)
                for w in reader_words:
                    if w and len(w) > 2 and w not in vm.skeleton(block_text) and vault_sorted["".join(sorted(w))] == 0 and w in page_skeleton:
                        pass  # the reader word belongs to another block of the page; not attributable without alignment
            order = ["not found", "word differences", "letters present in another order", "identical"]
            cls = next(c for c in order if c in cls_of_facets)
            counts[cls] += 1
            if cls in ("word differences", "not found"):
                details.append(f"- {vm.principle_id(vid, key)}: {cls}; words of the vault absent from the second reader: {', '.join(words_missing_vault[:8])}")
        result = "PASS" if counts["not found"] == 0 else "FAIL"
        lines += [f"RESULT: {result}", "", "second reader: pdftotext (Poppler)", f"principles compared: {sum(counts.values())}", ""]
        lines += [f"- {k}: {v}" for k, v in sorted(counts.items())]
        lines += ["", "Differences are read by a person and never change the vault.", ""] + details
        _write_report(project, vid, f"crosscheck-r{run}", "\n".join(lines))
        print("\n".join(lines[:12]))
        rc |= 0 if result == "PASS" else 1
    return rc


