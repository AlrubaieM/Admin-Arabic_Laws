def _tesseract_path() -> str | None:
    env = os.environ.get("PRINCIPLES_VAULT_TESSERACT")
    if env and Path(env).exists():
        return env
    return shutil.which("tesseract")


# number and page cells: Western and Arabic-Indic digits (the page prints the latter), the Arabic and Latin comma, space
OCR_DIGIT_WHITELIST = "0123456789٠١٢٣٤٥٦٧٨٩،, "


OCR_LINE_MODES = (7, 13)


def ocr_command(tool: str, png: Path, psm: int, whitelist: str | None = None) -> list[str]:
    cmd = [tool, str(png), "stdout", "-l", "ara", "--oem", "1", "--psm", str(psm)]
    if whitelist:
        cmd += ["-c", f"tessedit_char_whitelist={whitelist}"]
    return cmd


def line_crop_rect(line, cell, pad: float = 3.0, inset: float = 1.5) -> tuple[float, float, float, float]:
    """The line's box padded by `pad`, clipped to the cell interior so the table rulings stay out of the crop."""
    return (max(line.x0 - pad, cell.x0 + inset), max(line.y0 - pad, cell.y0 + inset),
            min(line.x1 + pad, cell.x1 - inset), min(line.y1 + pad, cell.y1 - inset))


def ocr_text(raw: str) -> str:
    """Tesseract output as a comparable line: bidi marks removed, then the reader's normalization (digits, NFC), trimmed."""
    return ps.normalize_text(RE_BIDI_MARKS.sub("", raw)).strip()


def _ocr(tool: str, png: Path, psm: int, whitelist: str | None = None) -> str:
    env = dict(os.environ, OMP_THREAD_LIMIT="1")  # one thread per Tesseract process; lines run in parallel
    res = subprocess.run(ocr_command(tool, png, psm, whitelist), capture_output=True, text=True, encoding="utf-8", errors="replace", env=env)
    return ocr_text(res.stdout)


def _ocr_readings(tool: str, png: Path, published: str, digit_cell: bool) -> tuple[bool, list[str]]:
    """Single text line (psm 7), then raw line (psm 13): psm 7 returns nothing on some lines of this layout.
    A line is confirmed only when one reading equals the published skeleton exactly."""
    readings: list[str] = []
    for psm in OCR_LINE_MODES:
        readings.append(_ocr(tool, png, psm, OCR_DIGIT_WHITELIST if digit_cell else None))
        if vm.skeleton(readings[-1]) == vm.skeleton(published):
            return True, readings
    return False, readings


def cmd_ocr_confirm(project, volume_ids: list[str], build_volume_files) -> int:
    tool = _tesseract_path()
    for vid in volume_ids:
        out = project.work / "review" / f"ocr-{vid}.yaml"
        if tool is None:
            print(f"{vid}: OCR confirmation blocked: tesseract not found (PRINCIPLES_VAULT_TESSERACT, PATH); no record written")
            continue
        cfg = project.load_config(vid)
        decisions = cfg.get("decisions") or {}
        vb, _files = build_volume_files(project, vid)
        crops = project.work / "review" / "crops" / vid
        crops.mkdir(parents=True, exist_ok=True)
        confirmed = disagreeing = decided = auto_kept = 0
        items = []
        cells_by_page: dict[tuple[str, int], set[tuple[int, int]]] = {}
        for key, p in vb.principles.items():
            for f in p.facets:
                for sl in _block_lines(vb, f):
                    if sl.row is not None:
                        cells_by_page.setdefault((f.file, sl.page), set()).add((sl.row, sl.col))
        docs: dict[str, pymupdf.Document] = {}
        fmaps: dict = {}
        paths = {Path(project.source_path(vid, e)).name: project.source_path(vid, e) for e in cfg.get("source_files") or []}
        jobs: list[tuple[str, Path, str, bool, str, int]] = []
        with tempfile.TemporaryDirectory() as tmp:
            for (file_name, pno) in sorted(cells_by_page):
                if file_name not in docs:
                    docs[file_name] = pymupdf.open(str(paths[file_name]))
                    fmaps[file_name] = vb.font_maps(docs[file_name], paths[file_name])
                doc = docs[file_name]
                fm, repairs = fmaps[file_name]
                glyphs = ps.page_glyphs(doc, pno, fm, repairs, vb.settings)
                table = ps.segment_table(pno, ps.merge_rulings(ps.page_rulings(doc[pno - 1])), glyphs, vb.settings)
                if table is None:
                    continue
                for (row, col) in sorted(cells_by_page[(file_name, pno)]):
                    cell = next((c for r in table.rows if r.index == row for c in r.cells if c.col == col), None)
                    if cell is None or not cell.lines:
                        continue
                    digit_cell = col in (1, 2)
                    # one crop per line, so every comparison is keyed by the line's own location (page[P]:r:c:Lk);
                    # crops are rendered here (pymupdf is not thread-safe) and read by Tesseract in parallel below
                    for k, line in enumerate(cell.lines):
                        png = Path(tmp) / f"p{pno}-r{row}-c{col}-L{k}.png"
                        ps.render_crop(doc, pno, line_crop_rect(line, cell), png, dpi=400, pad=0)
                        jobs.append((f"page[{pno}]:r{row}:c{col}:L{k}", png, line.text, digit_cell, file_name, pno))
            workers = max(1, min(8, (os.cpu_count() or 2) - 1))
            with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
                results = list(pool.map(lambda job: _ocr_readings(tool, job[1], job[2], job[3]), jobs))  # in job order
            second = _pdftotext_path()
            second_pages: dict[tuple[str, int], str] = {}
            for (loc, png, pub, _digit, file_name, pno), (ok, readings) in zip(jobs, results):
                if ok:
                    confirmed += 1
                    continue
                item_id = hashlib.sha256(f"{vid}|{loc}|wording".encode("utf-8")).hexdigest()[:12]
                if item_id in decisions:
                    decided += 1
                    continue
                disagreeing += 1
                crop_path = crops / f"{item_id}.png"
                shutil.copy(png, crop_path)
                item = {"item_id": item_id, "issue_type": "wording", "location": loc, "published": pub, "ocr": " | ".join(r for r in readings if r),
                        "crop": crop_path.relative_to(project.root).as_posix(),
                        "options": ["keep the text-layer reading (decision keep)", "publish the OCR reading (decision ocr)"]}
                # project rule 1 (best accurate result, automatically): the published reading is kept without a manual
                # decision when the independent second reader confirms every number and word of the line on its page
                if second is not None:
                    if (file_name, pno) not in second_pages:
                        second_pages[(file_name, pno)] = pdftotext_page(second, paths[file_name], pno)
                    if second_reader_confirms(pub, second_pages[(file_name, pno)]):
                        auto_kept += 1
                        item["resolution"] = "auto_keep"
                        item["basis"] = "the second reader (Poppler pdftotext) finds every number and word of the published line on the page; OCR misreads it"
                items.append(item)
        for doc in docs.values():
            doc.close()
        data = {"volume_id": vid, "confirmed": confirmed, "disagreeing": disagreeing, "decided": decided, "auto_kept": auto_kept,
                "unacknowledged": disagreeing - auto_kept, "items": items}
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(em.dump_yaml(data), encoding="utf-8", newline="\n")
        print(f"{vid}: OCR confirmed {confirmed}, disagreeing {disagreeing} (kept automatically, confirmed by the second reader: {auto_kept}; "
              f"left for review: {disagreeing - auto_kept}), decided {decided}")
    return 0
